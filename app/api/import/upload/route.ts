import { NextResponse } from "next/server";
import { getSessionUser } from "@/lib/auth/session";
import { hasPermission } from "@/lib/auth/permissions";
import { importService } from "@/server/services/import.service";

export async function POST(request: Request) {
  try {
    const session = await getSessionUser();
    if (!hasPermission(session?.roleCode, "importManage")) {
      return NextResponse.json({ error: "Import management access is required to upload normalized inventory CSV files." }, { status: 403 });
    }

    const formData = await request.formData();
    const file = formData.get("file");

    if (!(file instanceof File)) {
      return NextResponse.json({ error: "Missing file field." }, { status: 400 });
    }

    if (!file.name.toLowerCase().endsWith(".csv")) {
      return NextResponse.json(
        { error: "Inventory import now accepts only the normalized migration_template_inventory.csv contract generated by the Python migration script." },
        { status: 400 },
      );
    }

    if (file.name.toLowerCase().includes("_spl")) {
      return NextResponse.json(
        { error: "This looks like a splitter upload. Use the Splitters Inventory import flow so splitter records stay separate from transport inventory." },
        { status: 400 },
      );
    }

    const templateVersion = formData.get("templateVersion") ? String(formData.get("templateVersion")) : null;
    const sourceSystem = formData.get("sourceSystem") ? String(formData.get("sourceSystem")) : null;

    const buffer = Buffer.from(await file.arrayBuffer());
    const result = await importService.stageNormalizedInventoryCsv({
      fileName: file.name,
      workbookBuffer: buffer,
      uploadedById: session!.id,
      templateVersion: templateVersion ?? "normalized-inventory-csv-v1",
      sourceSystem: sourceSystem ?? "python-normalized-migration-template",
    });

    return NextResponse.json(result);
  } catch (error) {
    return NextResponse.json(
      { error: error instanceof Error ? error.message : "Normalized CSV import upload failed." },
      { status: 500 },
    );
  }
}
