import { NextResponse } from "next/server";
import { getSessionUser } from "@/lib/auth/session";
import { hasPermission } from "@/lib/auth/permissions";
import { writeAuditLog } from "@/lib/audit/audit-log";
import { parseNormalizedInventoryCsv } from "@/lib/import/normalized-inventory-template";
import { prisma } from "@/lib/db/prisma";

// ── Single-pass import reliability (multi-click import bug fix) ──────────────
// This route previously wrapped the ENTIRE CSV in one interactive transaction
// running with Prisma's default 5s timeout. Any real-world file (hundreds of
// rows, each an upsert + create, plus a per-splitter recount pass) blew past
// that budget, the whole transaction rolled back, and the operator had to
// re-click Import hoping it would squeeze through. Rows are now committed in
// bounded chunks, each chunk with explicit generous limits and exponential-
// backoff retries for transient failures. Chunks are idempotent (upsert +
// find-or-update outputs), so a retried or re-imported file never duplicates
// splitter outputs the way the old blind `create` did.
const CHUNK_SIZE = 200;
const CHUNK_TX_OPTIONS = { maxWait: 15_000, timeout: 120_000 } as const;
const TRANSIENT_RETRY_DELAYS_MS = [250, 1_000, 4_000];

function isTransientDbError(error: unknown): boolean {
  const code = String((error as { code?: unknown })?.code ?? "");
  if (["P2028", "P2034", "P1008", "P1001", "P1002", "P1017"].includes(code)) return true;
  const message = error instanceof Error ? error.message.toLowerCase() : "";
  return ["deadlock", "serialization", "timed out", "timeout", "connection reset", "econnreset", "transaction already closed"]
    .some((needle) => message.includes(needle));
}

const sleep = (ms: number) => new Promise((resolve) => setTimeout(resolve, ms));

async function withTransientRetry<T>(operation: () => Promise<T>): Promise<T> {
  for (let attempt = 0; ; attempt += 1) {
    try {
      return await operation();
    } catch (error) {
      if (isTransientDbError(error) && attempt < TRANSIENT_RETRY_DELAYS_MS.length) {
        await sleep(TRANSIENT_RETRY_DELAYS_MS[attempt]);
        continue;
      }
      throw error;
    }
  }
}

function chunkRows<T>(rows: T[], size = CHUNK_SIZE): T[][] {
  const chunks: T[][] = [];
  for (let index = 0; index < rows.length; index += size) chunks.push(rows.slice(index, index + size));
  return chunks;
}

function normalizedProtectionMode(normalized: any): "PROTECTED" | "UNPROTECTED" | "UNKNOWN" {
  const raw = String(normalized.splitterProtectionMode ?? "").trim().toUpperCase();
  if (raw === "PROTECTED") return "PROTECTED";
  if (raw === "UNPROTECTED" || raw === "NON_PROTECTED" || raw === "NON PROTECTED") return "UNPROTECTED";
  const sourcePath = [
    normalized.sourceSiteRaw,
    normalized.sourceSiteCanonical,
    normalized.farSiteRaw,
    normalized.farSiteDisplay,
    normalized.farNamedLocation,
    normalized.splitterLocation,
    normalized.splitterLocationContext,
    normalized.segmentName,
  ]
    .filter(Boolean)
    .join(" ");
  return sourcePath.includes("&") ? "PROTECTED" : "UNKNOWN";
}

export async function POST(request: Request) {
  try {
    const session = await getSessionUser();
    if (!hasPermission(session?.roleCode, "importManage")) {
      return NextResponse.json({ error: "Import management access is required to import splitters." }, { status: 403 });
    }

    const formData = await request.formData();
    const file = formData.get("file");
    if (!(file instanceof File)) return NextResponse.json({ error: "Missing splitter CSV file." }, { status: 400 });
    if (!file.name.toLowerCase().endsWith(".csv")) {
      return NextResponse.json({ error: "Splitter import accepts normalized CSV files generated by the Python migration script." }, { status: 400 });
    }

    const parsed = parseNormalizedInventoryCsv(Buffer.from(await file.arrayBuffer()));
    let splittersTouched = 0;
    let outputsCreated = 0;
    const warnings: string[] = [];
    const splitterIdsTouched = new Set<string>();

    // COMMIT FIX: bounded chunk transactions (explicit limits + transient
    // retries) instead of one whole-file transaction on the 5s default budget.
    // Counters are per-attempt locals merged only after a chunk COMMITS, so a
    // retried (rolled-back) attempt can never double-count rows or warnings.
    for (const rowChunk of chunkRows(parsed.rows)) {
      const chunkResult = await withTransientRetry(async () => {
        const chunk = { splittersTouched: 0, outputsCreated: 0, warnings: [] as string[], splitterIds: new Set<string>() };
        await prisma.$transaction(async (tx) => {
      for (const row of rowChunk) {
        const normalized = row.normalized;
        const splitterCode = normalized.splitterCode ?? normalized.splitterRef ?? normalized.segmentName ?? `SPL-${row.rowNumber}`;
        if (!normalized.splitterRef) chunk.warnings.push(`Row ${row.rowNumber}: splitter_ref is blank; using ${splitterCode}.`);
        const splitter = await tx.splitter.upsert({
          where: { splitterCode },
          update: {
            splitterName: normalized.segmentName ?? splitterCode,
            splitterType: normalized.splitterTypeTag ?? `${normalized.splitterScope ?? "OSP"}_SPL`,
            scope: normalized.splitterScope ?? "OSP",
            location: normalized.splitterLocation ?? normalized.farNamedLocation ?? normalized.farSiteDisplay ?? null,
            locationContext: normalized.splitterLocationContext ?? normalized.splitterLocation ?? normalized.farNamedLocation ?? normalized.farSiteDisplay ?? null,
            protectionMode: normalizedProtectionMode(normalized),
            primaryInputSiteCode: normalized.sourceSiteCanonical ?? normalized.sourceSiteRaw,
            primaryInputRackCode: normalized.rackCode,
            primaryInputOdfCode: normalized.odfCode,
            primaryInputPortLabel: normalized.portGroupLabel,
            status: "ACTIVE",
            source: "IMPORT",
          },
          create: {
            splitterCode,
            splitterName: normalized.segmentName ?? splitterCode,
            splitterType: normalized.splitterTypeTag ?? `${normalized.splitterScope ?? "OSP"}_SPL`,
            scope: normalized.splitterScope ?? "OSP",
            location: normalized.splitterLocation ?? normalized.farNamedLocation ?? normalized.farSiteDisplay ?? null,
            locationContext: normalized.splitterLocationContext ?? normalized.splitterLocation ?? normalized.farNamedLocation ?? normalized.farSiteDisplay ?? null,
            protectionMode: normalizedProtectionMode(normalized),
            primaryInputSiteCode: normalized.sourceSiteCanonical ?? normalized.sourceSiteRaw,
            primaryInputRackCode: normalized.rackCode,
            primaryInputOdfCode: normalized.odfCode,
            primaryInputPortLabel: normalized.portGroupLabel,
            outputPortCapacity: normalized.segmentCapacityFibers ?? 32,
            configuredOutputPorts: 0,
            status: "ACTIVE",
            source: "IMPORT",
            sourceRowReferencesJson: JSON.stringify([{ fileName: file.name, rowNumber: row.rowNumber }]),
            remarks: normalized.issueReason,
          },
        });
        chunk.splittersTouched += 1;
        chunk.splitterIds.add(splitter.id);
        // DEDUPLICATION FIX: find-or-update instead of blind create. The old
        // unconditional `create` doubled every splitter output whenever the
        // operator re-clicked Import or re-uploaded the same CSV after a
        // partial failure. The physical identity of an output is its splitter
        // + output port + local ODF port + destination; one physical line must
        // exist exactly once regardless of how many times the file is imported.
        const outputData = {
          splitterId: splitter.id,
          outputLabel: normalized.unitIndex ? `Output ${normalized.unitIndex}` : normalized.portGroupLabel,
          outputPort: normalized.portGroupLabel,
          localSiteCode: normalized.sourceSiteCanonical ?? normalized.sourceSiteRaw,
          localRackCode: normalized.rackCode,
          localOdfCode: normalized.odfCode,
          localPortLabel: normalized.portGroupLabel,
          destinationSiteCode: normalized.farSiteCanonical,
          destinationLabel: normalized.farSiteDisplay ?? normalized.farNamedLocation ?? normalized.farSiteRaw,
          destinationRackCode: normalized.farRackCode,
          destinationOdfCode: normalized.farOdfCode,
          destinationPortLabel: normalized.farPortGroupLabel,
          serviceCode: normalized.serviceIdResolved,
          sharingCustomerServiceId: null,
          sharingCustomerServiceCode: null,
          capacityFibers: Math.max(1, normalized.localFiberCount ?? 1),
          usedFibers: normalized.serviceIdResolved ? Math.max(1, normalized.localFiberCount ?? 1) : 0,
          availableFibers: normalized.serviceIdResolved ? 0 : Math.max(1, normalized.localFiberCount ?? 1),
          status: normalized.serviceIdResolved ? "ACTIVE" : "AVAILABLE",
          remarks: normalized.issueReason,
        } as const;
        const existingOutput = await tx.splitterOutput.findFirst({
          where: {
            splitterId: splitter.id,
            outputPort: outputData.outputPort ?? null,
            localPortLabel: outputData.localPortLabel ?? null,
            destinationLabel: outputData.destinationLabel ?? null,
            serviceCode: outputData.serviceCode ?? null,
          },
          select: { id: true },
        });
        if (existingOutput) {
          await tx.splitterOutput.update({ where: { id: existingOutput.id }, data: outputData });
        } else {
          await tx.splitterOutput.create({ data: outputData });
          chunk.outputsCreated += 1;
        }
      }
        }, CHUNK_TX_OPTIONS);
        return chunk;
      });
      splittersTouched += chunkResult.splittersTouched;
      outputsCreated += chunkResult.outputsCreated;
      warnings.push(...chunkResult.warnings);
      for (const id of chunkResult.splitterIds) splitterIdsTouched.add(id);
    }

    // The recount runs AFTER all chunks in its own short transaction, so a huge
    // file never holds one giant transaction open across the whole import.
    await withTransientRetry(() => prisma.$transaction(async (tx) => {
      for (const splitterId of splitterIdsTouched) {
        const configuredOutputPorts = await tx.splitterOutput.count({ where: { splitterId, status: { not: "DECOMMISSIONED" } } });
        await tx.splitter.update({ where: { id: splitterId }, data: { configuredOutputPorts } });
      }
    }, CHUNK_TX_OPTIONS));

    await writeAuditLog({
      entityType: "Splitter",
      entityId: file.name,
      action: "IMPORT",
      newValue: { fileName: file.name, rows: parsed.rows.length, splittersTouched, outputsCreated, warnings: warnings.length },
      changedById: session?.id ?? null,
      reason: "Separate splitter CSV import",
    });

    return NextResponse.json({ fileName: file.name, rows: parsed.rows.length, splittersTouched, outputsCreated, warnings: warnings.slice(0, 100) });
  } catch (error) {
    return NextResponse.json({ error: error instanceof Error ? error.message : "Splitter import failed." }, { status: 500 });
  }
}
